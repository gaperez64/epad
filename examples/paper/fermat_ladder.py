#!/usr/bin/env python3
"""Generate the Fermat ladder coefficient samples used in the paper."""

from __future__ import annotations

import argparse
from math import prod
from pathlib import Path


DEFAULT_OUTPUT = (
    Path(__file__).resolve().parents[3]
    / "epad-nexp"
    / "generated"
    / "fermat_ladder.tex"
)


def fermat_ratio(h: int) -> int:
    """Return the forced ratio at height h."""
    if h < 0:
        raise ValueError("h must be nonnegative")
    return 2 ** (2**h) + 1


def mersenne_multiplier(j: int) -> int:
    """Return M_j = 2^(2^j) - 1."""
    if j < 0:
        raise ValueError("j must be nonnegative")
    return 2 ** (2**j) - 1


def verify(max_height: int = 8) -> None:
    """Check the Fermat product identity used by the ladder."""
    for height in range(max_height + 1):
        assert prod(fermat_ratio(q) for q in range(height)) == mersenne_multiplier(
            height
        )


def render(t: int = 3) -> str:
    """Render the generated LaTeX coefficient macros."""
    if t != 3:
        raise ValueError("the paper sample is intentionally fixed at t=3")
    verify(max_height=max(8, t))

    quotient_samples = ",".join(str(fermat_ratio(h)) for h in range(5))
    multiplier_samples = ",".join(str(mersenne_multiplier(j)) for j in range(1, 6))

    return "\n".join(
        [
            "% Generated by ../epad-normalizer/examples/paper/fermat_ladder.py.",
            "% Do not edit by hand; regenerate with generate_all.py.",
            f"\\providecommand{{\\FermatSurvivingQuotients}}{{\\({quotient_samples}\\)}}",
            f"\\providecommand{{\\MersenneProjectedCoefficients}}{{\\({multiplier_samples}\\)}}",
            "",
        ]
    )


def write(output: Path = DEFAULT_OUTPUT) -> Path:
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(render(), encoding="utf-8")
    return output


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    args = parser.parse_args()
    print(write(args.output))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
